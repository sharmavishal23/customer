"use client";

import Link from "next/link";
import { useMemo, useState } from "react";
import { Check, Download, Eye, Search, Upload } from "lucide-react";
import { PAGE, PageHeader } from "@/components/AppShell";
import { DOC_ICON, DocPreview, cx } from "@/components/shipment";
import { ALL_SHIPMENTS, formatTime, type Doc, type Shipment } from "@/lib/data";
import { useStore } from "@/lib/store";

type Row = { doc: Doc; s: Shipment; key: string };

const TYPES: { key: Doc["kind"] | "all"; label: string }[] = [
  { key: "all", label: "All documents" },
  { key: "awb", label: "Air Waybills" },
  { key: "booking", label: "Booking confirmations" },
  { key: "invoice", label: "Commercial invoices" },
  { key: "packing", label: "Packing lists" },
  { key: "pod", label: "Proofs of delivery" },
];

const TONE: Record<Doc["kind"], string> = {
  awb: "bg-blue-50 text-blue-600",
  booking: "bg-violet-50 text-violet-600",
  invoice: "bg-amber-50 text-amber-600",
  packing: "bg-slate-100 text-slate-600",
  pod: "bg-emerald-50 text-emerald-600",
};

function downloadDoc(r: Row) {
  const s = r.s;
  const text = [
    `${r.doc.name.toUpperCase()}`,
    `Issued by Airflo B.V.`,
    ``,
    `Shipment:          ${s.id}`,
    `AWB:               ${s.awb}`,
    `Shipper:           ${s.shipper}`,
    `Consignee:         ${s.consignee}`,
    `Route:             ${[s.origin, s.via, s.destination].filter(Boolean).join(" - ")}`,
    `Flight(s):         ${s.flights.join(", ")}`,
    `Pieces:            ${s.pieces}`,
    `Actual weight:     ${s.actualWeight} kg`,
    `Chargeable weight: ${s.chargeableWeight} kg`,
    `Commodity:         ${s.commodity}`,
    ``,
    `(Sample document generated by the Airflo portal prototype)`,
  ].join("\n");
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([text], { type: "text/plain" }));
  a.download = `${s.awb}-${r.doc.kind}.txt`;
  a.click();
  URL.revokeObjectURL(a.href);
}

export default function DocumentsPage() {
  const { t } = useStore();
  const [type, setType] = useState<Doc["kind"] | "all">("all");
  const [q, setQ] = useState("");
  const [selected, setSelected] = useState<Set<string>>(new Set());
  const [preview, setPreview] = useState<Row | null>(null);
  const [limit, setLimit] = useState(30);

  const all: Row[] = useMemo(
    () => ALL_SHIPMENTS.flatMap((s) => s.documents.map((doc) => ({ doc, s, key: `${s.id}-${doc.kind}` }))).sort((a, b) => +new Date(b.doc.date) - +new Date(a.doc.date)),
    [],
  );

  const rows = useMemo(() => {
    const qq = q.trim().toLowerCase().replace(/[\s-]/g, "");
    return all.filter((r) => {
      if (type !== "all" && r.doc.kind !== type) return false;
      if (!qq) return true;
      return [r.s.id, r.s.awb, r.s.reference, r.s.consignee, r.doc.name, r.s.destination].join(" ").toLowerCase().replace(/[\s-]/g, "").includes(qq);
    });
  }, [all, type, q]);

  const toggle = (k: string) =>
    setSelected((prev) => {
      const n = new Set(prev);
      if (n.has(k)) n.delete(k);
      else n.add(k);
      return n;
    });

  const visible = rows.slice(0, limit);
  const allVisibleSelected = visible.length > 0 && visible.every((r) => selected.has(r.key));

  return (
    <main className={PAGE}>
      <PageHeader
        title={t("documents")}
        subtitle="All shipping documents in one place — no more searching through email."
        actions={
          <>
            <button className="inline-flex items-center gap-1.5 rounded-lg bg-white px-3 py-2 text-xs font-semibold text-slate-700 ring-1 ring-slate-200 hover:bg-slate-50">
              <Upload className="h-3.5 w-3.5" /> Upload document
            </button>
            <button
              disabled={selected.size === 0}
              onClick={() => all.filter((r) => selected.has(r.key)).forEach(downloadDoc)}
              className="inline-flex items-center gap-1.5 rounded-lg bg-slate-900 px-3 py-2 text-xs font-semibold text-white hover:bg-slate-800 disabled:cursor-not-allowed disabled:opacity-40"
            >
              <Download className="h-3.5 w-3.5" /> Download selected{selected.size ? ` (${selected.size})` : ""}
            </button>
          </>
        }
      />

      {/* Type summary */}
      <div className="mt-6 grid grid-cols-2 gap-3 sm:grid-cols-3 lg:grid-cols-6">
        {TYPES.map((tp) => {
          const n = tp.key === "all" ? all.length : all.filter((r) => r.doc.kind === tp.key).length;
          const I = tp.key === "all" ? DOC_ICON.awb : DOC_ICON[tp.key];
          const active = type === tp.key;
          return (
            <button
              key={tp.key}
              onClick={() => setType(tp.key)}
              className={cx("rounded-2xl bg-white p-4 text-left ring-1 transition", active ? "ring-2 ring-blue-600" : "ring-slate-200 hover:ring-slate-300")}
            >
              <span className={cx("grid h-8 w-8 place-items-center rounded-lg", tp.key === "all" ? "bg-slate-900 text-white" : TONE[tp.key])}>
                <I className="h-4 w-4" />
              </span>
              <div className="mt-3 text-xl font-semibold text-slate-900">{n}</div>
              <div className="truncate text-xs text-slate-500">{tp.label}</div>
            </button>
          );
        })}
      </div>

      <div className="mt-4 overflow-hidden rounded-2xl bg-white ring-1 ring-slate-200">
        <div className="flex flex-col gap-3 border-b border-slate-100 p-4 sm:flex-row sm:items-center sm:justify-between">
          <div className="relative w-full sm:max-w-sm">
            <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-slate-400" />
            <input
              value={q}
              onChange={(e) => setQ(e.target.value)}
              placeholder="Search by AWB, shipment, reference…"
              className="h-9 w-full rounded-lg bg-slate-50 pl-9 pr-3 text-sm outline-none ring-1 ring-slate-200 focus:bg-white focus:ring-2 focus:ring-blue-500"
            />
          </div>
          <span className="text-xs text-slate-500">{rows.length} documents</span>
        </div>

        <ul className="divide-y divide-slate-100">
          <li className="hidden items-center gap-4 bg-slate-50/60 px-4 py-2.5 text-[11px] font-semibold uppercase tracking-wide text-slate-500 md:flex">
            <button
              onClick={() =>
                setSelected((prev) => {
                  const n = new Set(prev);
                  visible.forEach((r) => (allVisibleSelected ? n.delete(r.key) : n.add(r.key)));
                  return n;
                })
              }
              className={cx("grid h-4 w-4 place-items-center rounded border", allVisibleSelected ? "border-blue-600 bg-blue-600 text-white" : "border-slate-300 bg-white")}
              aria-label="Select all"
            >
              {allVisibleSelected && <Check className="h-3 w-3" />}
            </button>
            <span className="flex-1">Document</span>
            <span className="w-40">{t("shipment")}</span>
            <span className="w-28">{t("route")}</span>
            <span className="w-32">Added</span>
            <span className="w-20 text-right">Actions</span>
          </li>
          {visible.map((r) => {
            const I = DOC_ICON[r.doc.kind];
            const on = selected.has(r.key);
            return (
              <li key={r.key} className={cx("flex flex-wrap items-center gap-x-4 gap-y-1 px-4 py-3 transition md:flex-nowrap", on ? "bg-blue-50/50" : "hover:bg-slate-50")}>
                <button
                  onClick={() => toggle(r.key)}
                  className={cx("grid h-4 w-4 shrink-0 place-items-center rounded border", on ? "border-blue-600 bg-blue-600 text-white" : "border-slate-300 bg-white")}
                  aria-label="Select"
                >
                  {on && <Check className="h-3 w-3" />}
                </button>
                <div className="flex min-w-0 flex-1 items-center gap-3">
                  <span className={cx("grid h-9 w-9 shrink-0 place-items-center rounded-lg", TONE[r.doc.kind])}>
                    <I className="h-4 w-4" />
                  </span>
                  <div className="min-w-0">
                    <div className="truncate text-sm font-medium text-slate-800">{r.doc.name}</div>
                    <div className="text-[11px] text-slate-400">PDF · {r.doc.size}</div>
                  </div>
                </div>
                <div className="w-40 text-sm">
                  <Link href={`/shipments/${r.s.id}`} className="font-semibold text-slate-800 hover:text-blue-600">
                    {r.s.id}
                  </Link>
                  <div className="font-mono text-[11px] text-slate-400">{r.s.awb}</div>
                </div>
                <div className="w-28 text-sm font-medium text-slate-700">
                  {r.s.origin} → {r.s.destination}
                </div>
                <div className="w-32 text-xs text-slate-500">{formatTime(r.doc.date, r.s.origin)}</div>
                <div className="ml-auto flex w-20 justify-end gap-1">
                  <button onClick={() => setPreview(r)} className="grid h-8 w-8 place-items-center rounded-lg text-slate-500 hover:bg-slate-100 hover:text-slate-900" aria-label={t("view")}>
                    <Eye className="h-4 w-4" />
                  </button>
                  <button onClick={() => downloadDoc(r)} className="grid h-8 w-8 place-items-center rounded-lg text-slate-500 hover:bg-slate-100 hover:text-slate-900" aria-label="Download">
                    <Download className="h-4 w-4" />
                  </button>
                </div>
              </li>
            );
          })}
          {rows.length === 0 && <li className="px-4 py-16 text-center text-sm text-slate-500">No documents match your search.</li>}
        </ul>
        {rows.length > limit && (
          <button onClick={() => setLimit(limit + 30)} className="block w-full border-t border-slate-100 py-3 text-center text-xs font-semibold text-blue-600 hover:bg-slate-50">
            Show more ({rows.length - limit} remaining)
          </button>
        )}
      </div>

      {preview && <DocPreview doc={preview.doc} s={preview.s} onClose={() => setPreview(null)} />}
    </main>
  );
}
